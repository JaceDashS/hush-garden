export const TEXTS: Record<Language, Record<TextKey, string>> = { ko, en, ja };

/** The text for a key in a language, with `{name}` parts replaced from `values`. */
export function translate(language: Language, key: TextKey, values?: Record<string, string | number>): string {
  const text = TEXTS[language][key] ?? ko[key];
  return values ? text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole)) : text;
}

/** Any stored value becomes a known language; `fallback` is used for anything else. */
export function normalizeLanguage(value: unknown, fallback: Language = "ko"): Language {
  return LANGUAGES.includes(value as Language) ? (value as Language) : fallback;
}

/** The app language for a device locale such as "ja-JP": its language when the app has it, otherwise English. */
export function languageForLocale(locale: unknown): Language {
  const code = typeof locale === "string" ? locale.toLowerCase().split(/[-_]/)[0] : "";
  return normalizeLanguage(code, "en");
}
